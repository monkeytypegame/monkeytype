export type WallpaperVariantInfo = {
  id: WallpaperThemeVariant;
  name: string;
};

export const wallpaperThemeVariants: WallpaperVariantInfo[] = [
  { id: "tonal-spot", name: "Tonal Spot" },
  { id: "vibrant", name: "Vibrant" },
  { id: "expressive", name: "Expressive" },
  { id: "content", name: "Content" },
  { id: "neutral", name: "Neutral" },
  { id: "monochrome", name: "Monochrome" },
  { id: "fidelity", name: "Fidelity" },
  { id: "rainbow", name: "Rainbow" },
  { id: "fruit-salad", name: "Fruit Salad" },
];

type SchemeFactory = new (
  source: Hct,
  isDark: boolean,
  contrastLevel: number,
) => DynamicScheme;

function schemeForVariant(
  variant: WallpaperThemeVariant,
  source: Hct,
  isDark: boolean,
  contrastLevel = 0,
): DynamicScheme {
  const schemeByVariant: Partial<Record<WallpaperThemeVariant, SchemeFactory>> =
    {
      "tonal-spot": SchemeTonalSpot,
      expressive: SchemeExpressive,
      content: SchemeContent,
      neutral: SchemeNeutral,
      monochrome: SchemeMonochrome,
      fidelity: SchemeFidelity,
      rainbow: SchemeRainbow,
      "fruit-salad": SchemeFruitSalad,
    };
  // the vibrant variant never reaches this function: it is generated by the
  // Noctalia port in vibrantColorsFromImage instead of a Material scheme
  return new (schemeByVariant[variant] ?? SchemeTonalSpot)(
    source,
    isDark,
    contrastLevel,
  );
}

function argbToHex(argb: number): string {
  return hexFromArgb(argb);
}

/**
 * How strongly a variant should tint the otherwise neutral surface colors.
 * Material 3 surfaces are intentionally close to gray, which on Monkeytype
 * reads as "nothing changed" - the wallpaper is barely noticeable. These
 * multipliers keep the hue of the wallpaper visible in backgrounds, buttons
 * and secondary text while staying readable.
 */
const variantTintStrength: Record<WallpaperThemeVariant, number> = {
  "tonal-spot": 1.35,
  vibrant: 2,
  expressive: 1.8,
  content: 1.5,
  neutral: 0.55,
  monochrome: 0.12,
  fidelity: 1.6,
  rainbow: 1.9,
  "fruit-salad": 1.8,
};

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Builds an HCT color from a hue/chroma/tone triple, letting HCT gamut-map it. */
function tintedColor(hue: number, chroma: number, tone: number): number {
  return Hct.from(hue, clamp(chroma, 0, 120), clamp(tone, 0, 100)).toInt();
}

/**
 * Untyped words are rendered in the sub color, so a palette that puts it too
 * close to the background makes the test hard to read. Pull its chroma partway
 * towards the palette's main color so it still reads as a muted version of the
 * accent, then push the tone away from the background towards the text color
 * (brighter on dark palettes, darker on light ones).
 */
export function readableSub(
  hex: string,
  mainHex: string,
  mode: WallpaperThemeMode,
): string {
  const hct = Hct.fromInt(argbFromHex(hex));
  const main = Hct.fromInt(argbFromHex(mainHex));
  const chroma = hct.chroma + (main.chroma - hct.chroma) * 0.35;
  const step = 12;
  const tone =
    mode === "dark"
      ? Math.min(hct.tone + step, 86)
      : Math.max(hct.tone - step, 14);
  return argbToHex(tintedColor(hct.hue, chroma, tone));
}

/**
 * Map a Material 3 scheme to Monkeytype's 10 theme color slots:
 * [bg, main, caret, sub, subAlt, text, error, errorExtra, colorfulError, colorfulErrorExtra]
 *
 * The accent slots come straight from the scheme, but the surface slots are
 * re-derived from the wallpaper hue with extra chroma: Material's own surfaces
 * are near-gray and would not visibly change the page.
 */
function schemeToMonkeytypeColors(
  scheme: DynamicScheme,
  mode: WallpaperThemeMode,
  variant: WallpaperThemeVariant,
): CustomThemeColors {
  const primary = Hct.fromInt(scheme.primary);
  const strength = variantTintStrength[variant] ?? 1.35;
  const hue = primary.hue;

  // accents keep the wallpaper hue, guaranteed to be clearly saturated
  const accentChroma = Math.max(primary.chroma, 48 * Math.min(strength, 1.6));
  const main = tintedColor(hue, accentChroma, Hct.fromInt(scheme.primary).tone);
  const caret = tintedColor(
    Hct.fromInt(scheme.tertiary).hue,
    Math.max(Hct.fromInt(scheme.tertiary).chroma, accentChroma * 0.85),
    Hct.fromInt(scheme.tertiary).tone,
  );

  if (mode === "dark") {
    // dark tinted surfaces: visible hue, still comfortably dark
    const surfaceChroma = clamp(6 + strength * 7, 6, 26);
    const bg = tintedColor(hue, surfaceChroma, 7);
    const subAlt = tintedColor(hue, surfaceChroma * 0.85, 13);
    const sub = tintedColor(hue, clamp(4 + strength * 5, 4, 20), 55);
    const text = tintedColor(hue, clamp(3 + strength * 2, 3, 12), 92);

    return [
      argbToHex(bg),
      argbToHex(main),
      argbToHex(caret),
      argbToHex(sub),
      argbToHex(subAlt),
      argbToHex(text),
      argbToHex(scheme.error),
      argbToHex(scheme.onError),
      argbToHex(scheme.secondary),
      argbToHex(scheme.onSecondary),
    ] as CustomThemeColors;
  }

  // light tinted surfaces
  const surfaceChroma = clamp(5 + strength * 5, 5, 20);
  const bg = tintedColor(hue, surfaceChroma, 96);
  const subAlt = tintedColor(hue, surfaceChroma, 91);
  const sub = tintedColor(hue, clamp(4 + strength * 4, 4, 18), 45);
  const text = tintedColor(hue, clamp(3 + strength * 2, 3, 12), 12);

  return [
    argbToHex(bg),
    argbToHex(main),
    argbToHex(caret),
    argbToHex(sub),
    argbToHex(subAlt),
    argbToHex(text),
    argbToHex(scheme.error),
    argbToHex(scheme.onError),
    argbToHex(scheme.secondary),
    argbToHex(scheme.onSecondary),
  ] as CustomThemeColors;
}

async function loadImageElement(src: string): Promise<HTMLImageElement> {
  return await new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.decoding = "async";
    // a hung request would otherwise leave the panel loading forever
    const timeout = setTimeout(() => {
      reject(new Error("Timed out loading wallpaper image"));
    }, 15_000);
    img.onload = () => {
      clearTimeout(timeout);
      resolve(img);
    };
    img.onerror = () => {
      clearTimeout(timeout);
      reject(new Error("Failed to load wallpaper image"));
    };
    img.src = src;
  });
}

function pixelsFromImage(img: HTMLImageElement): number[] {
  const maxSize = 128;
  const scale = Math.min(1, maxSize / Math.max(img.width, img.height));
  const width = Math.max(1, Math.round(img.width * scale));
  const height = Math.max(1, Math.round(img.height * scale));
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  if (ctx === null) {
    throw new Error("Could not create canvas context for color extraction");
  }
  ctx.drawImage(img, 0, 0, width, height);
  const data = ctx.getImageData(0, 0, width, height).data;
  const pixels: number[] = [];
  for (let i = 0; i < data.length; i += 4) {
    const a = data[i + 3] ?? 255;
    if (a < 128) continue;
    const r = data[i] ?? 0;
    const g = data[i + 1] ?? 0;
    const b = data[i + 2] ?? 0;
    pixels.push(argbFromRgb(r, g, b));
  }
  if (pixels.length === 0) {
    throw new Error("No opaque pixels found in image");
  }
  return pixels;
}

/**
 * Picks the wallpaper's representative color.
 *
 * Material's `Score` weights chroma so heavily that a few vivid leaves can
 * win over the actual dominant colors of the image, which makes the page look
 * unrelated to the wallpaper. Instead: take the most common quantized colors
 * and choose the most colorful among them, weighted by how much of the image
 * they actually cover.
 */
export function sourceColorFromPixels(pixels: number[]): number {
  const quantized = QuantizerCelebi.quantize(pixels, 128);
  const entries = [...quantized.entries()];
  const fallback = [...entries].sort((a, b) => b[1] - a[1])[0];
  if (fallback === undefined) {
    throw new Error("Could not extract a source color from image");
  }

  // group the image's colors into hue families, weighted by how much of the
  // image each one covers, so the theme follows the dominant mood instead of
  // whichever single pixel happens to be the most saturated; hue sums are
  // circular so a family split across 0/360 is not counted twice
  const bins = new Map<
    number,
    { weight: number; chroma: number; sin: number; cos: number }
  >();
  for (const [argb, count] of entries) {
    const hct = Hct.fromInt(argb);
    if (hct.tone < 16 || hct.tone > 92 || hct.chroma < 6) continue;
    const bin = Math.round(hct.hue / 30) % 12;
    const weight = count * Math.sqrt(hct.chroma);
    const radians = (hct.hue * Math.PI) / 180;
    const current = bins.get(bin) ?? {
      weight: 0,
      chroma: 0,
      sin: 0,
      cos: 0,
    };
    current.weight += weight;
    current.chroma = Math.max(current.chroma, hct.chroma);
    current.sin += Math.sin(radians) * weight;
    current.cos += Math.cos(radians) * weight;
    bins.set(bin, current);
  }

  let bestBin: number | null = null;
  let bestBinWeight = -1;
  for (const [bin, data] of bins) {
    if (data.weight > bestBinWeight) {
      bestBinWeight = data.weight;
      bestBin = bin;
    }
  }

  if (bestBin === null) {
    return fallback[0];
  }

  // refine within the winning family (and its neighbours) so the hue does not
  // jump between adjacent buckets
  let sin = 0;
  let cos = 0;
  let chroma = 0;
  for (const offset of [0, -1, 1]) {
    const data = bins.get((bestBin + offset + 12) % 12);
    if (data === undefined) continue;
    sin += data.sin;
    cos += data.cos;
    chroma = Math.max(chroma, data.chroma);
  }

  let hue = (Math.atan2(sin, cos) * 180) / Math.PI;
  if (hue < 0) hue += 360;

  return Hct.from(hue, Math.min(90, Math.max(28, chroma)), 50).toInt();
}

/**
 * Reads every pixel of the image at its natural resolution. Noctalia's box
 * filter needs the original pixels: canvas downscaling would feed it a
 * differently filtered image and shift the clusters.
 */
function imageRgba(img: HTMLImageElement): {
  data: Uint8ClampedArray;
  width: number;
  height: number;
} {
  const width = img.naturalWidth || img.width;
  const height = img.naturalHeight || img.height;
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  if (ctx === null) {
    throw new Error("Could not read wallpaper pixels");
  }
  ctx.drawImage(img, 0, 0, width, height);
  return { data: ctx.getImageData(0, 0, width, height).data, width, height };
}

/**
 * Vibrant uses Noctalia's own generator instead of Material's SchemeVibrant so
 * the palette matches the desktop shell for the same wallpaper. The shared sub
 * color is adjusted afterwards like every other variant.
 */
function vibrantColorsFromImage(
  img: HTMLImageElement,
  mode: WallpaperThemeMode,
): CustomThemeColors {
  const { data, width, height } = imageRgba(img);
  const palette = generateNoctaliaVibrant(data, width, height, mode);
  return [
    palette.background,
    palette.primary,
    palette.primary,
    palette.onSurfaceVariant,
    palette.surfaceContainerLow,
    palette.onSurface,
    palette.error,
    palette.errorContainer,
    palette.secondary,
    palette.tertiary,
  ] as CustomThemeColors;
}

export function generateColorsForVariant(
  sourceArgb: number,
  variant: Exclude<WallpaperThemeVariant, "vibrant">,
  mode: WallpaperThemeMode,
): CustomThemeColors {
  const source = Hct.fromInt(sourceArgb);
  const scheme = schemeForVariant(variant, source, mode === "dark", 0);
  return schemeToMonkeytypeColors(scheme, mode, variant);
}

export type GeneratedScheme = {
  id: WallpaperThemeVariant;
  name: string;
  colors: CustomThemeColors;
};

export async function generateAllWallpaperSchemes(
  src: string,
  mode: WallpaperThemeMode,
): Promise<GeneratedScheme[]> {
  const img = await loadImageElement(src);
  const sourceArgb = sourceColorFromPixels(pixelsFromImage(img));
  const vibrant = vibrantColorsFromImage(img, mode);
  return wallpaperThemeVariants.map((v) => {
    const colors =
      v.id === "vibrant"
        ? vibrant
        : generateColorsForVariant(sourceArgb, v.id, mode);
    // the shared vibrant array is visited exactly once by this loop, so the
    // boost is applied a single time to every palette
    colors[3] = readableSub(colors[3], colors[1], mode);
    return { id: v.id, name: v.name, colors };
  });
}
